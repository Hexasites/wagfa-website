/* WAGFA website — WA State Records explorer.
   Reads window.WAGFA_RECORDS (generated by build.mjs into records-data.js). */
(() => {
  'use strict';
  const data = window.WAGFA_RECORDS;
  const root = document.getElementById('records-explorer');
  if (!data || !root) return;

  const MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const PAGE = 50;
  const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
  const fmtDate = (iso) => { const [y, m, d] = iso.split('-'); return `${Number(d)} ${MON[Number(m) - 1]} ${y}`; };
  const fmtKg = (n) => (n == null ? '—' : n.toLocaleString('en-AU', { minimumFractionDigits: 2, maximumFractionDigits: 3 }));
  const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

  const rows = data.rows.map((r) => {
    const rec = { species: data.species[r[0]], category: data.categories[r[1]], environment: data.environments[r[2]], line: r[3], first: r[4], surname: r[5], weight: r[6], location: r[7], date: r[8] };
    rec.angler = [rec.first, rec.surname].filter(Boolean).join(' ');
    rec.haystack = `${rec.species} ${rec.angler} ${rec.location}`.toLowerCase();
    return rec;
  });

  const $ = (id) => document.getElementById(id);
  const el = { q: $('rf-q'), species: $('rf-species'), category: $('rf-category'), line: $('rf-line'), environment: $('rf-environment'), sort: $('rf-sort'), reset: $('rf-reset'), count: $('rf-count'), body: $('rf-body'), more: $('rf-more'), csv: $('rf-csv'), empty: $('rf-empty') };
  const FILTERS = ['q', 'species', 'category', 'line', 'environment'];
  const catOrder = (c) => data.categories.indexOf(c);
  const sorters = {
    species: (a, b) => a.species.localeCompare(b.species) || catOrder(a.category) - catOrder(b.category) || a.line - b.line,
    heaviest: (a, b) => (b.weight ?? -1) - (a.weight ?? -1),
    newest: (a, b) => b.date.localeCompare(a.date),
    oldest: (a, b) => a.date.localeCompare(b.date),
  };

  let current = [];
  let shown = PAGE;

  // Restore filters from the URL so filtered views can be shared.
  const params = new URLSearchParams(location.search);
  [...FILTERS, 'sort'].forEach((k) => {
    const v = params.get(k);
    if (v == null || !el[k]) return;
    if (el[k].tagName === 'SELECT' && ![...el[k].options].some((o) => o.value === v || o.text === v)) return;
    el[k].value = v;
  });

  function apply() {
    const terms = el.q.value.trim().toLowerCase().split(/\s+/).filter(Boolean);
    current = rows.filter((r) =>
      (!el.species.value || r.species === el.species.value) &&
      (!el.category.value || r.category === el.category.value) &&
      (!el.line.value || String(r.line) === el.line.value) &&
      (!el.environment.value || r.environment === el.environment.value) &&
      terms.every((t) => r.haystack.includes(t)));
    current.sort(sorters[el.sort.value] || sorters.species);
    shown = PAGE;
    draw();
    syncUrl();
  }

  function draw() {
    el.body.innerHTML = current.slice(0, shown).map((r) => `<tr>
  <td class="species" data-label="Species">${esc(r.species)}</td>
  <td data-label="Category"><span class="badge badge--${slug(r.category)}">${esc(r.category)}</span></td>
  <td class="num" data-label="Line class">${r.line} kg</td>
  <td class="num weight" data-label="Weight">${fmtKg(r.weight)} kg</td>
  <td data-label="Angler">${esc(r.angler)}</td>
  <td data-label="Location">${esc(r.location)}</td>
  <td class="num" data-label="Date"><time datetime="${r.date}">${fmtDate(r.date)}</time></td>
  <td class="env" data-label="Environment">${esc(r.environment)}</td>
</tr>`).join('');
    const total = rows.length.toLocaleString('en-AU');
    el.count.textContent = current.length === rows.length ? `Showing all ${total} records` : `${current.length.toLocaleString('en-AU')} of ${total} records match`;
    const remaining = current.length - shown;
    el.more.hidden = remaining <= 0;
    el.more.textContent = `Show ${Math.min(PAGE, remaining)} more (${remaining} remaining)`;
    el.empty.hidden = current.length > 0;
    el.csv.disabled = current.length === 0;
  }

  function syncUrl() {
    const p = new URLSearchParams();
    FILTERS.forEach((k) => { if (el[k].value) p.set(k, el[k].value); });
    if (el.sort.value !== 'species') p.set('sort', el.sort.value);
    const qs = p.toString();
    history.replaceState(null, '', `${location.pathname}${qs ? `?${qs}` : ''}${location.hash}`);
  }

  function downloadCsv() {
    const cell = (v) => { const s = String(v ?? ''); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
    const lines = [['Species', 'Category', 'Environment', 'Line class (kg)', 'First name', 'Surname', 'Weight (kg)', 'Location', 'Date']]
      .concat(current.map((r) => [r.species, r.category, r.environment, r.line, r.first, r.surname, r.weight ?? '', r.location, r.date]))
      .map((row) => row.map(cell).join(','));
    const blob = new Blob(['﻿' + lines.join('\r\n')], { type: 'text/csv;charset=utf-8' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'wa-state-records-filtered.csv';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 500);
  }

  let timer;
  el.q.addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(apply, 140); });
  ['species', 'category', 'line', 'environment', 'sort'].forEach((k) => el[k].addEventListener('change', apply));
  el.reset.addEventListener('click', (e) => { e.preventDefault(); FILTERS.forEach((k) => { el[k].value = ''; }); el.sort.value = 'species'; apply(); el.q.focus(); });
  el.more.addEventListener('click', () => { shown += PAGE; draw(); });
  el.csv.addEventListener('click', downloadCsv);

  // Category shortcuts above the explorer filter in place instead of reloading.
  document.querySelectorAll('.cat-count[data-category]').forEach((a) => a.addEventListener('click', (e) => {
    e.preventDefault();
    el.category.value = a.dataset.category;
    apply();
    root.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }));

  apply();
})();
